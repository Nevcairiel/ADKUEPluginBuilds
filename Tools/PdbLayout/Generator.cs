// Generator: writes C++ declarations of ARK-only classes (types that exist only in the devkit, e.g. the new base
// classes UPrimalActor / UPrimalActorComponent that ARK inserted below AActor / UActorComponent).
//
//   PdbLayout genclass <arkpdb> <out.h> <sdkRoot> <apiMacro> <include>;<include>... <Type>...
//
// For each type: the devkit's base classes, the data members as opaque storage of the devkit's exact size (the
// plugin never touches ARK-only members by name, and ARK exports the constructors/destructors that own them), and
// every virtual function the type declares - introduced ones in vtable order, overrides of base class virtuals -
// so that classes derived from it (in the SDK and in plugins) get the devkit's vtable layout. Reflected classes
// (U*/A* derived from UObject, I* interfaces with a U* partner) are declared as UCLASS/UINTERFACE so UHT accepts
// them as bases of the engine classes; their generated code is never compiled (only the .generated.h is used).
// Types used in the signatures are forward declared (class/struct key taken from the SDK or the devkit PDB, which
// decides the mangled names), ARK-only enums as opaque enums with the devkit's underlying type.
using System.Text;
using System.Text.RegularExpressions;

static class Generator
{
    public static int Run(string[] args)
    {
        var db = TypeDb.Open(args[1]);
        var outPath = args[2];
        var sdkRoot = args[3];
        var api = args[4];
        var includes = args[5].Split(';', StringSplitOptions.RemoveEmptyEntries);
        var types = args.Skip(6).ToList();
        var sdk = SdkTypeIndex.Load(sdkRoot);

        var body = new StringBuilder();
        var used = new SortedSet<string>(StringComparer.Ordinal);
        var defined = new HashSet<string>(types);
        var problems = new List<string>();
        foreach (var name in types)
        {
            var t = db.Describe(name) ?? throw new Exception($"{name} not found in {args[1]}");
            body.Append(Declare(db, t, api, used, problems));
            // UINTERFACE partner: UFoo for IFoo
            if (name.StartsWith("I") && db.Describe("U" + name[1..]) != null) defined.Add("U" + name[1..]);
        }

        var sb = new StringBuilder();
        var headerName = Path.GetFileNameWithoutExtension(outPath);
        sb.Append("// Generated by Tools\\New-ArkClassHeaders.ps1 from the devkit PDBs (see Config\\ArkClasses.txt) - do not edit.\r\n");
        sb.Append("// ARK-only classes: devkit base classes, data members as opaque storage of the devkit's size, all virtual\r\n");
        sb.Append("// functions in vtable order. Checked by Tools\\Test-ArkAbi.ps1 like every other type.\r\n");
        sb.Append("#pragma once\r\n\r\n");
        foreach (var inc in includes) sb.Append($"#include \"{inc}\"\r\n");
        bool reflected = types.Any(n => IsReflected(db, n));
        if (reflected) sb.Append($"#include \"{headerName}.generated.h\"\r\n");
        sb.Append("\r\n");
        var fwd = ForwardDeclarations(db, sdk, used, defined, problems);
        if (fwd.Length > 0) sb.Append("// types used in the virtual function signatures\r\n").Append(fwd).Append("\r\n");
        sb.Append(body);
        File.WriteAllText(outPath, sb.ToString());
        Console.WriteLine($"wrote {outPath}: {string.Join(", ", types)}");
        foreach (var p in problems) Console.WriteLine("  CHECK: " + p);
        return 0;
    }

    static bool IsUObject(TypeDb db, string name)
    {
        for (int depth = 0; name != null && depth < 64; depth++)
        {
            if (name is "UObject" or "UObjectBase" or "UObjectBaseUtility") return true;
            var t = db.Describe(name);
            name = t?.Members.FirstOrDefault(m => m.Kind == "base")?.Type;
        }
        return false;
    }

    static bool IsReflected(TypeDb db, string name) =>
        IsUObject(db, name) || name.StartsWith("I") && db.Describe("U" + name[1..]) is TypeLayout u && IsUObject(db, u.Name);

    static readonly HashSet<string> Generated = new()
    {
        // declared by GENERATED_BODY / UHT or the compiler
        "StaticClass", "GetPrivateStaticClass", "StaticRegisterNatives", "__DefaultConstructor", "__VTableCtorCaller",
        "operator new", "operator delete", "operator=", "__vecDelDtor", "_getUObject", "ValidateGeneratedRepEnums",
        "StaticPackage", "StaticClassCastFlags", "StaticConfigName", "AddReferencedObjects",
    };

    static string Declare(TypeDb db, TypeLayout t, string api, SortedSet<string> used, List<string> problems)
    {
        var sb = new StringBuilder();
        bool uobj = IsUObject(db, t.Name);
        var partner = t.Name.StartsWith("I") ? db.Describe("U" + t.Name[1..]) : null;
        bool iface = partner != null && IsUObject(db, partner.Name);
        if (iface)
        {
            // UINTERFACE partner class (no members of its own besides UHT generated ones)
            sb.Append($"UINTERFACE(MinimalAPI)\r\nclass {partner.Name} : public {partner.Members.First(m => m.Kind == "base").Type}\r\n{{\r\n\tGENERATED_BODY()\r\n}};\r\n\r\n");
        }
        // empty bases (ARK mixins like PrimalLiveTunablesMixin<T>: no data, no vtable) do not affect the layout
        var bases = t.Members.Where(m => m.Kind == "base" && !(db.Describe(m.Type) is TypeLayout bt && bt.Size == 1
                                         && !bt.Members.Any(x => x.Kind is "data" or "bitfield" or "vfptr" or "base"))).ToList();
        var key = t.Kind == "struct" ? "struct" : "class";
        if (uobj) sb.Append("UCLASS()\r\n");
        sb.Append($"{key} {api} {t.Name}");
        if (bases.Count > 0) sb.Append(" : " + string.Join(", ", bases.Select(b => "public " + CppType.Clean(b.Type))));
        sb.Append("\r\n{\r\n");
        if (uobj || iface) sb.Append("\tGENERATED_BODY()\r\n");
        sb.Append("public:\r\n");
        var access = "public";   // the devkit's access of each virtual function (part of its mangled name)

        // ---- data: opaque, from the end of the bases to the end of the type
        var data = t.Members.Where(m => m.Kind is "data" or "bitfield").ToList();
        // Replication base (the first class with replicated properties): UHT declares NetPushId_Internal, the push id
        // accessors, GetLifetimeReplicatedProps and the rep index enum (REPLICATED_BASE_CLASS) in its GENERATED_BODY.
        // ARK made UPrimalActor the replication base of AActor; one replicated placeholder property (the last byte of
        // the opaque data, so the layout does not change) makes UHT do the same here and not in AActor.
        bool replBase = uobj && data.Any(m => m.Name == "NetPushId_Internal");
        if (replBase) data.RemoveAll(m => m.Name == "NetPushId_Internal");
        // other classes with replicated properties (ValidateGeneratedRepEnums, e.g. APrimalPawn): the same placeholder
        // makes UHT declare their GetLifetimeReplicatedProps / ValidateGeneratedRepEnums overrides
        bool replicated = replBase || uobj && t.Members.Any(m => m.Kind == "method" && m.Name == "ValidateGeneratedRepEnums");
        if (data.Count > 0)
        {
            long start = data.Min(m => m.Offset);
            long size = t.Size - start;
            sb.Append($"\t// {data.Count} data members at +0x{start:X}..+0x{t.Size:X} (ARK only, not accessed by plugins)\r\n");
            if (replicated)
            {
                sb.Append($"\talignas(8) uint8 ArkData_{t.Name}[0x{size - 1:X}];\r\n");
                sb.Append(replBase ? "\t// makes UHT generate the replication base declarations (NetPushId_Internal at the start of the class)\r\n"
                                   : "\t// makes UHT declare the replication overrides (GetLifetimeReplicatedProps, ValidateGeneratedRepEnums)\r\n");
                // (UHT does not allow a property to shadow one of a base class: one name per class)
                sb.Append($"\tUPROPERTY(Replicated)\r\n\tuint8 {(replBase ? "ArkReplicationBase" : "ArkReplicated_" + t.Name)};\r\n");
            }
            else sb.Append($"\talignas(8) uint8 ArkData_{t.Name}[0x{size:X}];\r\n");
        }

        // ---- introduced virtual functions in vtable order
        var intro = t.Members.Where(m => m.Kind == "method" && m.Intro && !Generated.Contains(m.Name) && !m.CompilerGenerated && !m.Name.StartsWith("~"))
                             .OrderBy(m => m.VSlot).ToList();
        if (intro.Count > 0)
        {
            sb.Append("\t// introduced virtual functions (devkit vtable order)\r\n");
            var done = new HashSet<Member>();
            foreach (var m in intro)
            {
                if (done.Contains(m)) continue;
                // MSVC groups overloads at the first declaration and lays them out in reverse declaration order
                var group = intro.Where(o => o.Name == m.Name).OrderByDescending(o => o.VSlot).ToList();
                foreach (var g in group) { sb.Append(Access(g, ref access)).Append($"\t{Method(g, used)}\r\n"); done.Add(g); }
            }
        }
        // ---- overrides of base class virtuals (they do not change the vtable layout, but its entries)
        // (_getUObject of interface implementers is declared by UHT, see Generated)
        var replGenerated = new HashSet<string> { "SetNetPushIdDynamic", "GetNetPushIdDynamic", "GetLifetimeReplicatedProps" };
        var overrides = t.Members.Where(m => m.Kind == "method" && m.Virtual && !m.Intro && !m.CompilerGenerated
                                             && !Generated.Contains(m.Name) && !m.Name.StartsWith("~")
                                             && !(replBase && replGenerated.Contains(m.Name))
                                             && !(replicated && m.Name == "GetLifetimeReplicatedProps")).ToList();
        if (overrides.Count > 0)
        {
            sb.Append("\t// overridden virtual functions\r\n");
            foreach (var m in overrides) sb.Append(Access(m, ref access)).Append($"\t{Method(m, used)}\r\n");
        }
        sb.Append("};\r\n\r\n");
        if (t.Members.Any(m => m.Kind == "method" && m.Pure)) problems.Add($"{t.Name} has pure virtual functions");
        return sb.ToString();
    }

    static string Access(Member m, ref string current)
    {
        var a = m.Access is "private" or "protected" ? m.Access : "public";
        if (a == current) return "";
        current = a;
        return a + ":\r\n";
    }

    static string Method(Member m, SortedSet<string> used)
    {
        var decl = CppType.MethodDecl(m);
        var (args, _, ret) = CppType.SplitSignature(m.Signature);
        foreach (Match id in Regex.Matches(CppType.Clean(ret) + " " + CppType.Clean(args), @"(?<![\w:])((?:\w+::)*[A-Z]\w*)\b(?!\s*<)")) used.Add(id.Groups[1].Value);   // not templates
        return decl;
    }

    static readonly HashSet<string> Builtin = new() { "FVector", "FVector2D", "FRotator", "FQuat", "FTransform", "FBox", "FMatrix", "FIntPoint", "TCHAR" };

    static string ForwardDeclarations(TypeDb db, SdkTypeIndex sdk, SortedSet<string> used, HashSet<string> defined, List<string> problems)
    {
        var sb = new StringBuilder();
        foreach (var name in used)
        {
            if (defined.Contains(name) || Builtin.Contains(name) || Regex.IsMatch(name, @"^T[A-Z]\w*$") && sdk.Kind(name) == null && db.Describe(name) == null) continue;
            var sdkKind = sdk.Kind(name);
            if (sdkKind is "class" or "struct") { sb.Append(Fwd(name, sdkKind, null)); continue; }
            if (sdkKind != null) continue;   // enum / typedef / alias: comes with the includes
            var t = db.Describe(name);
            if (t == null)
            {
                // namespace enum (EFoo::Type) or nested type
                var parent = name.Contains("::") ? name[..name.LastIndexOf("::")] : null;
                if (parent == null || sdk.Kind(parent) == null) problems.Add($"unknown type {name}: declare it in Config\\ArkForwardDeclarations.h");
                continue;
            }
            if (t.Kind == "enum") sb.Append(Fwd(name, "enum", t.Size switch { 1 => "uint8", 2 => "uint16", 8 => "uint64", _ => "int32" }));
            else if (t.Kind is "class" or "struct") sb.Append(Fwd(name, t.Kind, null));
            else problems.Add($"{name}: {t.Kind}");
        }
        return sb.ToString();
    }

    // gentypes <out.h> <sdkRoot> <extraHeader> <arkpdb>... : declarations of the ARK-only types that the patched SDK headers use
    // ([ARK] lines, generated ARK classes). Enums: opaque with the devkit's underlying type. Reflected classes (U*/A*):
    // forward declarations. Other structs/classes: opaque definitions with the devkit's size and alignment (they are
    // members by value of patched types; their code lives in the devkit, plugins only need the right layout).
    // The output is force-included through Config\ArkForwardDeclarations.h, before any engine header.
    public static int RunTypes(string[] args)
    {
        var outPath = args[1];
        var sdkRoot = args[2];
        var dbs = args.Skip(4).Select(TypeDb.Open).ToList();
        TypeLayout Find(string n) => dbs.Select(d => d.Describe(n)).FirstOrDefault(x => x != null);
        var sdk = SdkTypeIndex.Load(sdkRoot, Path.GetFullPath(outPath), args[3]);   // + ConfigArkForwardDeclarations.h

        // identifiers on [ARK] lines of the SDK headers and in the generated ARK classes
        var ids = new SortedSet<string>(StringComparer.Ordinal);
        // type names (not functions, not templates), including UE namespace enums EFoo::Type
        var idRe = new Regex(@"(?<![\w:])([FUAEI][A-Z]\w*::Type|(?:[A-Za-z_]\w*::)*[FUAEI][A-Z]\w*)\b(?!\s*[(<])");
        foreach (var f in Directory.EnumerateFiles(sdkRoot, "*.h", SearchOption.AllDirectories))
        {
            if (Path.GetFullPath(f) == Path.GetFullPath(outPath)) continue;
            bool arkFile = f.Replace('/', '\\').Contains("\\Public\\Ark\\");
            foreach (var line in File.ReadLines(f))
            {
                if (!arkFile && !line.Contains("[ARK]")) continue;
                var code = Regex.Replace(line, @"//.*$", "");
                foreach (Match m in idRe.Matches(code)) ids.Add(m.Groups[1].Value);
            }
        }

        var enums = new StringBuilder(); var fwds = new StringBuilder(); var defs = new StringBuilder();
        var problems = new List<string>();
        foreach (var name in ids)
        {
            var sdkKind = sdk.Kind(name);
            // SDK classes/structs used by a patched header may not be included there: a forward declaration (with the
            // SDK's class/struct key) covers pointers and references; by-value uses need an #include (manual edit)
            if (sdkKind is "class" or "struct" && !name.Contains("::") && !sdk.IsAliasOrNamespace(name) && !Builtin.Contains(name)) { fwds.Append(Fwd(name, Find(name)?.Kind is "class" or "struct" ? Find(name).Kind : sdkKind, null)); continue; }   // the devkit's key decides the mangling
            if (sdkKind != null || Builtin.Contains(name)) continue;
            var t = Find(name);
            if (t == null) { if (!name.Contains("::")) problems.Add($"{name}: not defined in the SDK and not found in the devkit PDBs"); continue; }
            if (name.Contains("::") && Find(name[..name.LastIndexOf("::")]) is TypeLayout p && p.Kind != "namespace")
            { problems.Add($"{name}: nested in {p.Name}, declare it by hand"); continue; }
            if (t.Kind == "enum") enums.Append(Fwd(name, "enum", t.Size switch { 1 => "unsigned char", 2 => "unsigned short", 8 => "unsigned long long", _ => "int" }));
            else if (name[0] is 'U' or 'A' || name[0] == 'I' && Find("U" + name[1..]) != null) fwds.Append(Fwd(name, t.Kind, null));
            else if (t.Members.Any(m => m.Kind is "vfptr" || m.Kind == "method" && m.Virtual))
                fwds.Append(Fwd(name, t.Kind, null));   // polymorphic: used by pointer (a base or by-value use needs Config\ArkClasses.txt)
            else
            {
                long align = AlignOf(Find, t.Name, 0);
                var key = t.Kind == "struct" ? "struct" : "class";
                var parts = name.Split("::");
                var def = $"{key} alignas({align}) {parts[^1]} {{ {(key == "class" ? "public: " : "")}unsigned char ArkData[{t.Size}]; }};";
                defs.Append(parts.Length == 1 ? def + "\r\n" : $"namespace {string.Join("::", parts[..^1])} {{ {def} }}\r\n");
            }
        }
        var sb = new StringBuilder();
        sb.Append("// Generated by Tools\\New-ArkClassHeaders.ps1 (PdbLayout gentypes) - do not edit.\r\n");
        sb.Append("// ARK-only types used by the patched SDK headers ([ARK] lines): opaque enums with the devkit's underlying type,\r\n");
        sb.Append("// forward declarations of reflected classes and opaque structs with the devkit's size and alignment.\r\n");
        sb.Append("// Force-included before any engine header through Config\\ArkForwardDeclarations.h.\r\n#pragma once\r\n\r\n");
        sb.Append(enums).Append("\r\n").Append(fwds).Append("\r\n").Append(defs);
        File.WriteAllText(outPath, sb.ToString());
        Console.WriteLine($"wrote {outPath}");
        foreach (var p in problems) Console.WriteLine("  CHECK: " + p);
        return 0;
    }

    // alignment of a type from its PDB layout (largest alignment of its bases and members)
    static readonly Dictionary<string, long> alignCache = new();
    internal static long AlignOf(Func<string, TypeLayout> find, string type, int depth)
    {
        type = type.Trim();
        if (type.EndsWith("*") || type.EndsWith("&")) return 8;
        var arr = Regex.Match(type, @"^(.*)\[\d+\]$"); if (arr.Success) return AlignOf(find, arr.Groups[1].Value, depth);
        type = Regex.Replace(type, @"^(const |volatile )+", "");
        switch (type)
        {
            case "bool": case "char": case "signed char": case "unsigned char": case "char8_t": return 1;
            case "short": case "unsigned short": case "wchar_t": case "char16_t": return 2;
            case "int": case "unsigned int": case "long": case "unsigned long": case "float": case "char32_t": return 4;
            case "__int64": case "unsigned __int64": case "double": return 8;
        }
        if (alignCache.TryGetValue(type, out var c)) return c;
        if (depth > 32) return 8;
        var t = find(type);
        if (t == null) return 8;
        long a = t.Kind == "enum" ? Math.Max(1, t.Size) : 1;
        foreach (var m in t.Members)
        {
            if (m.Kind == "vfptr") a = Math.Max(a, 8);
            else if (m.Kind is "base" or "data" or "bitfield") a = Math.Max(a, AlignOf(find, m.Type, depth + 1));
        }
        return alignCache[type] = a;
    }

    static string Fwd(string name, string kind, string underlying)
    {
        var parts = name.Split("::");
        var decl = kind == "enum" ? $"enum {parts[^1]} : {underlying};" : $"{kind} {parts[^1]};";
        if (parts.Length == 1) return decl + "\r\n";
        var ns = string.Join("::", parts[..^1]);
        // EFoo::Type: UE namespace enum
        return $"namespace {ns} {{ {decl} }}\r\n";
    }
}

// Names of types defined in the SDK headers (class/struct/enum definitions, typedefs, using aliases).
sealed class SdkTypeIndex
{
    readonly Dictionary<string, string> kinds = new(StringComparer.Ordinal);
    // UE namespace enums (EFoo::Type) are looked up by their namespace, everything else by its last name segment
    public string Kind(string name)
    {
        var parts = name.Split("::");
        var key = parts.Length > 1 && parts[^1] == "Type" ? parts[^2] : parts[^1];
        return kinds.TryGetValue(key, out var k) ? k : null;
    }
    static readonly Regex NamespaceDef = new(@"^\s*namespace\s+([A-Za-z_]\w*)\s*(\{|$)", RegexOptions.Compiled);

    static readonly Regex Def = new(@"^\s*(?:template\s*<[^>]*>\s*)?(class|struct)\s+(?:alignas\([^)]*\)\s+)?(?:[A-Z][A-Z0-9_]*_API\s+)?(?:UE_DEPRECATED\([^)]*\)\s+)?([A-Za-z_]\w*)\s*(?:final\s*)?(?::[^;]*)?$|^\s*(?:template\s*<[^>]*>\s*)?(class|struct)\s+(?:[A-Z][A-Z0-9_]*_API\s+)?([A-Za-z_]\w*)\s*(?:final\s*)?(?::[^;{]*)?\{", RegexOptions.Compiled);
    static readonly Regex EnumDef = new(@"^\s*enum\s+(?:class\s+|struct\s+)?([A-Za-z_]\w*)\b", RegexOptions.Compiled);
    static readonly Regex Alias = new(@"^\s*(?:typedef\s+.*\b([A-Za-z_]\w*)\s*;|using\s+([A-Za-z_]\w*)\s*=)", RegexOptions.Compiled);
    static readonly Regex DelegateMacro = new(@"^\s*DECLARE_(?:DYNAMIC_)?(?:MULTICAST_)?(?:SPARSE_)?(?:TS_)?(?:DELEGATE|EVENT)\w*\(\s*(?:\w+\s*,\s*)?([A-Za-z_]\w*)", RegexOptions.Compiled);

    public static SdkTypeIndex Load(string root, string skip = null, params string[] extraFiles)
    {
        var idx = new SdkTypeIndex();
        var files = Directory.EnumerateFiles(root, "*.h", SearchOption.AllDirectories).Where(f => skip == null || Path.GetFullPath(f) != skip).Concat(extraFiles);
        foreach (var f in files)
        {
            foreach (var line in File.ReadLines(f))
            {
                Match m;
                if ((m = Def.Match(line)).Success)
                {
                    var kind = m.Groups[1].Success ? m.Groups[1].Value : m.Groups[3].Value;
                    var name = m.Groups[2].Success ? m.Groups[2].Value : m.Groups[4].Value;
                    idx.kinds[name] = kind;   // a definition wins over aliases of the same name
                }
                else if ((m = EnumDef.Match(line)).Success) idx.kinds.TryAdd(m.Groups[1].Value, "enum");
                else if ((m = Alias.Match(line)).Success) idx.kinds.TryAdd(m.Groups[1].Success ? m.Groups[1].Value : m.Groups[2].Value, "alias");
                else if ((m = DelegateMacro.Match(line)).Success) idx.kinds.TryAdd(m.Groups[1].Value, "alias");
                else if ((m = NamespaceDef.Match(line)).Success)
                {
                    if (m.Groups[1].Value.StartsWith("E")) idx.kinds.TryAdd(m.Groups[1].Value, "enum");
                    idx.namespaces.Add(m.Groups[1].Value);
                }
                if ((m = Alias.Match(line)).Success) idx.aliases.Add(m.Groups[1].Success ? m.Groups[1].Value : m.Groups[2].Value);
            }
        }
        return idx;
    }

    // names that are a typedef/alias or a namespace somewhere in the SDK must never be forward declared as a class
    readonly HashSet<string> aliases = new(StringComparer.Ordinal), namespaces = new(StringComparer.Ordinal);
    public bool IsAliasOrNamespace(string name) => aliases.Contains(name) || namespaces.Contains(name);
}
