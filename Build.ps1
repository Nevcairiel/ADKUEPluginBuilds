<#
.SYNOPSIS
  Builds ShooterGameEditor-<Module>.dll of every module of one plugin folder for the ARK Devkit with MSVC.

.DESCRIPTION
  1. Refreshes the shared ARK SDK (headers + ARK patches) and runs UnrealHeaderTool for engine + plugin.
  2. Remaps reflection flag literals in the plugin's generated code to the devkit's enum values.
  3. Compiles all plugin sources with the compiler settings UBT uses for UE 5.8 editor modules.
  4. Links against import libraries of the devkit's ShooterGameEditor-*.dll files (and, in a multi-module
     plugin, the import libraries of the plugin modules linked before).
  5. Stages a ready-to-install plugin folder in <Plugin>\Build\Output\<PluginName>.
.EXAMPLE
  .\Build.ps1 BlueprintAssist
  .\Build.ps1 BlueprintAssist -Rebuild
#>
param(
    [Parameter(Position = 0)] [string] $Plugin,   # plugin folder name below Plugins
    [switch] $Clean,
    [switch] $Rebuild,
    [switch] $CompileOnly,   # stop after compiling (used by Tools\Test-LayoutIndependence.ps1)
    [switch] $ForceLink,     # link despite unresolved externals (/FORCE:UNRESOLVED): only to get a PDB to patch the SDK from
    [int]    $Jobs = [Environment]::ProcessorCount
)
. "$PSScriptRoot\Common.ps1"
Initialize-Plugin $Plugin
$sw = [Diagnostics.Stopwatch]::StartNew()
Write-Host "Plugin $PluginName ($PluginRoot), modules $($ModuleNames -join ', ')"

$pluginGenerated = Join-Path $IntDir 'Inc'
$linkDir = Join-Path $IntDir 'Bin'
if ($Clean) {
    foreach ($d in (Join-Path $IntDir 'Obj'), $pluginGenerated, $OutDir) { if (Test-Path $d) { Remove-Item -Recurse -Force $d } }
    if (-not $Rebuild) { return }
}
$msvc = Find-Msvc
Write-Host "MSVC $($msvc.Version)"
Update-PluginSource   # patched copy of the sources if the plugin has Build\SourcePatches

# --- 1. SDK + UHT ----------------------------------------------------------------------------------------------
if (-not (Test-Path (Join-Path $SdkRoot 'Lib'))) { & "$BuildDir\New-ArkSdk.ps1" } else { & "$BuildDir\New-ArkSdk.ps1" -HeadersOnly }
# Modules without reflected types (no UhtPluginModule.json, see Capture-UbtBaseline.ps1) have no UHT step
$uhtModules = @($ModuleNames | Where-Object { Test-Path (Join-Path (Get-ModuleConfigDir $_) 'UhtPluginModule.json') })
if ($uhtModules) {
    Write-Step 'UnrealHeaderTool'
    & "$BuildDir\Invoke-Uht.ps1" $PluginRoot

    # --- 2. generated code fix-ups -----------------------------------------------------------------------------
    Write-Step 'Adjusting generated code for the devkit'
    foreach ($m in $uhtModules) { & "$BuildDir\Tools\Update-GeneratedCode.ps1" -GeneratedDir (Join-Path $pluginGenerated "$m\UHT") }
}

$stageModules = [ordered]@{}
foreach ($module in $ModuleNames) {
Select-PluginModule $module
if ($IsMultiModule) { Write-Step "Module $ModuleName" }
New-Item -ItemType Directory -Force $ObjDir | Out-Null

if ($module -in $uhtModules) {
    # Unity file for the generated reflection code (as UBT does)
    $uhtOut = Join-Path $pluginGenerated "$ModuleName\UHT"
    $genUnity = Join-Path $ObjDir "Module.$ModuleName.gen.cpp"
    $genContent = @('// Generated by Build.ps1: includes all UHT generated cpp files') +
        (Get-ChildItem $uhtOut -Filter *.gen.cpp | Sort-Object Name | ForEach-Object { "#include `"$($_.FullName.Replace('\', '/'))`"" })
    if (-not (Test-Path $genUnity) -or ((Get-Content $genUnity) -join "`n") -ne ($genContent -join "`n")) { Set-Content $genUnity $genContent }
}
else { $genUnity = @() }
# per-module allocator hooks
$perModule = Join-Path $ObjDir 'PerModuleInline.gen.cpp'
if (-not (Test-Path $perModule)) {
    Set-Content $perModule @(
        '#if !defined(PER_MODULE_INLINE_FILE) && defined(CORE_API)',
        '#define PER_MODULE_INLINE_FILE "HAL/PerModuleInline.inl"',
        '#endif',
        '#if defined(PER_MODULE_INLINE_FILE) && !defined(SUPPRESS_PER_MODULE_INLINE_FILE)',
        '#include PER_MODULE_INLINE_FILE',
        '#endif')
}

# --- 3. compile ------------------------------------------------------------------------------------------------
Write-Step 'Compiling'
$moduleRebuild = [bool]$Rebuild
$rsp = [Collections.Generic.List[string]]::new()
$rsp.AddRange([string[]](Get-Content "$ConfigDir\CompilerFlags.rsp"))
foreach ($line in Get-Content "$ConfigDir\IncludePaths.txt") {
    if ($line.StartsWith('external ')) { $rsp.Add("/external:I `"$(Expand-ConfigPath $line.Substring(9) $pluginGenerated)`"") }
    else { $rsp.Add("/I `"$(Expand-ConfigPath $line $pluginGenerated)`"") }
}
foreach ($i in $msvc.Includes) { $rsp.Add("/external:I `"$i`"") }
$rsp.Add("/FI`"$ConfigDir\Definitions.h`"")
$rsp.Add("/FI`"$SharedConfigDir\ArkForwardDeclarations.h`"")
$sharedPchFile = Join-Path $ConfigDir 'SharedPch.h'   # modules that UBT builds with a shared PCH, see Capture-UbtBaseline.ps1
if (Test-Path $sharedPchFile) { $rsp.Add("/FI`"$sharedPchFile`"") }
$rspPath = Join-Path $ObjDir 'Compile.rsp'
$rspText = $rsp -join "`r`n"
if (-not (Test-Path $rspPath) -or (Get-Content $rspPath -Raw).Trim() -ne $rspText.Trim()) { Set-Content $rspPath $rspText; $moduleRebuild = $true }

$sources = @(Get-ChildItem (Join-Path $PluginSourceRoot $ModuleName) -Recurse -Filter *.cpp | ForEach-Object FullName) + $genUnity + $perModule
# cl names objects after the file name: two sources with the same name in one module would overwrite each other
$dupes = @($sources | Group-Object { [IO.Path]::GetFileName($_) } | Where-Object Count -gt 1)
if ($dupes) { throw "Source file names must be unique within a module: $($dupes.Name -join ', ')" }
# remove objects of source files that no longer exist (e.g. after updating the plugin sources)
$expected = $sources | ForEach-Object { [IO.Path]::GetFileName($_) + '.obj' }
Get-ChildItem $ObjDir -Filter *.obj | Where-Object { $_.Name -notin $expected } | ForEach-Object {
    Remove-Item $_.FullName, ($_.FullName -replace '\.obj$', '.json') -ErrorAction SilentlyContinue
}
# The SDK stamps count as configuration: a re-created SDK copies the vanilla headers with their original (old)
# timestamps, which the per-include check below would not notice
$sdkStamps = (Join-Path $SdkRoot '.ark-patches'), (Join-Path $SdkRoot 'Engine\Source\Runtime\Core\Public\Ark\ArkTypes.h')
$configStamp = @(Get-Item (@("$ConfigDir\Definitions.h", $rspPath, "$ConfigDir\SharedPch.h") + $sdkStamps) -ErrorAction SilentlyContinue | ForEach-Object LastWriteTimeUtc) | Sort-Object | Select-Object -Last 1

function Test-UpToDate([string] $src) {
    $base = [IO.Path]::GetFileName($src)
    $obj = Join-Path $ObjDir "$base.obj"; $dep = Join-Path $ObjDir "$base.json"
    if ($moduleRebuild -or -not (Test-Path $obj) -or -not (Test-Path $dep)) { return $false }
    $t = (Get-Item $obj).LastWriteTimeUtc
    if ($t -lt $configStamp -or $t -lt (Get-Item $src).LastWriteTimeUtc) { return $false }
    foreach ($inc in (Get-Content $dep -Raw | ConvertFrom-Json).Data.Includes) {
        if (-not (Test-Path $inc) -or (Get-Item $inc).LastWriteTimeUtc -gt $t) { return $false }
    }
    return $true
}
$dirty = @($sources | Where-Object { -not (Test-UpToDate $_) })
Write-Host "  $($dirty.Count) of $($sources.Count) files to compile"
if ($dirty.Count -gt 0) {
    # cl names objects <base>.obj inside /Fo<dir>\; give every file its own name via a per-batch rsp
    $batchRsp = Join-Path $ObjDir 'Sources.rsp'
    Set-Content $batchRsp ($dirty | ForEach-Object { "`"$_`"" })
    $logFile = Join-Path $ObjDir 'Compile.log'
    & $msvc.Cl "@$rspPath" "/MP$Jobs" "/Fo$ObjDir\" "/sourceDependencies" "$ObjDir\" "@$batchRsp" *> $logFile
    $clExit = $LASTEXITCODE
    # cl writes <base>.obj and <base>.json; rename to <file>.cpp.obj / .cpp.json so names stay unique and stable
    foreach ($s in $dirty) {
        $b = [IO.Path]::GetFileNameWithoutExtension($s); $n = [IO.Path]::GetFileName($s)
        foreach ($ext in 'obj', 'json') {
            $from = Join-Path $ObjDir "$b.$ext"; $to = Join-Path $ObjDir "$n.$ext"
            if (Test-Path $from) { Move-Item -Force $from $to }
        }
    }
    $errors = Get-Content $logFile | Where-Object { $_ -match ': (fatal )?error ' }
    if ($clExit -ne 0 -or $errors) {
        $errors | ForEach-Object { $_ -replace ' \(compiling source file [^)]*\)', '' } | Sort-Object -Unique | Select-Object -First 60 | Out-Host
        throw "Compilation of $ModuleName failed ($(@($errors).Count) errors), see $logFile"
    }
}

if ($CompileOnly) { continue }

# --- 4. link ---------------------------------------------------------------------------------------------------
Write-Step 'Linking'
$binName = "$ModulePrefix$ModuleName"
New-Item -ItemType Directory -Force $linkDir | Out-Null
$lrsp = [Collections.Generic.List[string]]::new()
$lrsp.AddRange([string[]](Get-Content "$ConfigDir\LinkerFlags.rsp"))
foreach ($l in $msvc.LibPaths) { $lrsp.Add("/LIBPATH:`"$l`"") }
foreach ($s in $sources) { $lrsp.Add("`"$(Join-Path $ObjDir ([IO.Path]::GetFileName($s) + '.obj'))`"") }
foreach ($m in Get-Content "$ConfigDir\EngineModules.txt") {
    $lib = Join-Path $SdkRoot "Lib\$ModulePrefix$m.lib"
    if (Test-Path $lib) { $lrsp.Add("`"$lib`"") } else { Write-Host "  (devkit has no $m module, not linked)" }
}
# plugin modules linked before this one (Initialize-Plugin orders $ModuleNames accordingly)
foreach ($m in Get-Content "$ConfigDir\PluginModules.txt" -ErrorAction SilentlyContinue) { $lrsp.Add("`"$linkDir\$ModulePrefix$m.lib`"") }
foreach ($l in Get-Content "$ConfigDir\SystemLibs.txt") { $lrsp.Add("`"$l`"") }
foreach ($l in Get-Content "$ConfigDir\ThirdPartyLibs.txt" -ErrorAction SilentlyContinue) { $lrsp.Add("`"$(Join-Path $SdkRoot $l)`"") }
if ($ForceLink) { $lrsp.Add('/FORCE:UNRESOLVED') }
$lrsp.Add("/OUT:`"$linkDir\$binName.dll`"")
$lrsp.Add("/PDB:`"$linkDir\$binName.pdb`"")
$lrsp.Add("/IMPLIB:`"$linkDir\$binName.lib`"")
$linkRsp = Join-Path $linkDir "Link.$ModuleName.rsp"
$linkLog = Join-Path $linkDir "Link.$ModuleName.log"
Set-Content $linkRsp $lrsp
# link.exe merges into an existing PDB and would keep stale type records from previous builds
Remove-Item "$linkDir\$binName.pdb", "$linkDir\$binName.dll" -ErrorAction SilentlyContinue
& $msvc.Link "@$linkRsp" *> $linkLog
$linkExit = $LASTEXITCODE
$linkErrors = Get-Content $linkLog | Where-Object { $_ -match 'error LNK|warning LNK4217|warning LNK4286' }
if ($ForceLink -and (Test-Path "$linkDir\$binName.pdb")) { if ($linkExit -ne 0) { Write-Host "  forced link ($(@($linkErrors).Count) unresolved), the DLL is not usable" -ForegroundColor Yellow } }
elseif ($linkExit -ne 0) { $linkErrors | Select-Object -First 60 | Out-Host; throw "Link of $ModuleName failed, see $linkLog" }
$stageModules[$ModuleName] = "$binName.dll"
}
if ($CompileOnly) { Write-Step 'Compiled (link skipped)'; return }
if ($ForceLink) { Write-Step 'Reference build done (forced link, not staged)'; return }

# --- 5. stage ----------------------------------------------------------------------------------------------------
Write-Step 'Staging plugin'
$stage = Join-Path $OutDir $PluginName
$stageBin = Join-Path $stage 'Binaries\Win64'
New-Item -ItemType Directory -Force $stageBin | Out-Null
Copy-Item $UpluginPath $stage -Force
foreach ($d in 'Resources', 'Content', 'Config', 'Shaders', 'ThirdParty') {   # plugin folders UE loads at runtime (not Source/Build)
    if (Test-Path "$PluginRoot\$d") { Copy-Item "$PluginRoot\$d" $stage -Recurse -Force }
}
foreach ($dll in $stageModules.Values) { Copy-Item "$linkDir\$dll", ("$linkDir\$dll" -replace '\.dll$', '.pdb') $stageBin -Force }
$buildId = (Get-Content (Join-Path $DevkitBinaries 'ShooterGameEditor.modules') -Raw | ConvertFrom-Json).BuildId
$modules = [ordered]@{ BuildId = $buildId; Modules = $stageModules }
$modules | ConvertTo-Json | Set-Content (Join-Path $stageBin 'ShooterGameEditor.modules')
Write-Step ("Done in {0:n0}s -> {1}" -f $sw.Elapsed.TotalSeconds, $stage)
